"""Prepare SteamOS's local resolver entry point in its offline /etc view."""
import os
from pathlib import Path
import stat
from uuid import uuid4

from file_transaction import directory_fd


RESOLVER = 'resolv.conf'
STUB = '/run/systemd/resolve/stub-resolv.conf'


def verify(root):
    directory = directory_fd(Path(root) / 'etc')
    try:
        try:
            target = os.readlink(RESOLVER, dir_fd=directory)
        except OSError as error:
            raise ValueError('SteamOS DNS must use the local systemd-resolved stub') from error
        if target != STUB:
            raise ValueError('SteamOS DNS stub link differs from the prepared configuration')
        return {'resolver_link': target, 'upstream': 'automatic'}
    finally:
        os.close(directory)


def prepare(root):
    """Replace a stock resolver file atomically, preserving unknown policies."""
    directory = directory_fd(Path(root) / 'etc')
    try:
        try:
            info = os.stat(RESOLVER, dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            info = None
        if info is not None:
            if stat.S_ISLNK(info.st_mode):
                target = os.readlink(RESOLVER, dir_fd=directory)
                if target == STUB:
                    return
                if target != '..' + STUB:
                    raise ValueError('Existing SteamOS resolver link requires review: /etc/resolv.conf')
            elif stat.S_ISREG(info.st_mode):
                flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
                with os.fdopen(os.open(RESOLVER, flags, dir_fd=directory), 'rb') as stream:
                    if not stat.S_ISREG(os.fstat(stream.fileno()).st_mode):
                        raise ValueError('Unexpected SteamOS resolver file type: /etc/resolv.conf')
                    data = stream.read(4097)
                lines = data.splitlines()
                if len(data) > 4096 or (lines[:1] != [b'# Generated by NetworkManager'] and
                        any(line.strip() and not line.lstrip().startswith((b'#', b';')) for line in lines)):
                    raise ValueError('Existing SteamOS DNS settings require review: /etc/resolv.conf')
            else:
                raise ValueError('Unexpected SteamOS resolver file type: /etc/resolv.conf')

        temporary = '.boiler-resolv-' + uuid4().hex
        os.symlink(STUB, temporary, dir_fd=directory)
        try:
            os.replace(temporary, RESOLVER, src_dir_fd=directory, dst_dir_fd=directory)
            os.fsync(directory)
        finally:
            try:
                os.unlink(temporary, dir_fd=directory)
            except FileNotFoundError:
                pass
    finally:
        os.close(directory)
