import os
from pathlib import Path
import tempfile
import unittest
from unittest import mock

if os.name == 'posix':
    import steam_dns


@unittest.skipUnless(os.name == 'posix', 'requires Linux resolver links and directory descriptors')
class SteamDnsTests(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.root = Path(directory.name)
        (self.root / 'etc').mkdir()
        self.resolver = self.root / 'etc/resolv.conf'

    def test_prepares_stock_and_missing_files_before_boot(self):
        sources = (b'# Resolver configuration file.\n',
                   b'# Generated by NetworkManager\nsearch lan\nnameserver 192.168.2.1\n',
                   None)
        for source in sources:
            with self.subTest(source=source):
                self.resolver.unlink(missing_ok=True)
                if source is not None:
                    self.resolver.write_bytes(source)
                steam_dns.prepare(self.root)
                steam_dns.verify(self.root)
                self.assertEqual(os.readlink(self.resolver), steam_dns.STUB)
                self.assertFalse((self.root / steam_dns.STUB.lstrip('/')).exists())

    def test_normalizes_the_equivalent_relative_link_and_retries_without_replacing_it(self):
        self.resolver.symlink_to('..' + steam_dns.STUB)
        steam_dns.prepare(self.root)
        before = self.resolver.lstat().st_ino
        steam_dns.prepare(self.root)
        steam_dns.verify(self.root)
        self.assertEqual(self.resolver.lstat().st_ino, before)

    def test_leaves_custom_resolver_settings_and_link_targets_intact(self):
        custom = b'nameserver 10.0.0.23\n'
        self.resolver.write_bytes(custom)
        with self.assertRaisesRegex(ValueError, 'DNS settings require review'):
            steam_dns.prepare(self.root)
        self.assertEqual(self.resolver.read_bytes(), custom)
        self.resolver.unlink()
        elsewhere = self.root / 'external-resolver'
        elsewhere.write_bytes(custom)
        self.resolver.symlink_to(elsewhere)
        with self.assertRaisesRegex(ValueError, 'resolver link requires review'):
            steam_dns.prepare(self.root)
        with self.assertRaisesRegex(ValueError, 'stub link differs'):
            steam_dns.verify(self.root)
        self.assertEqual(elsewhere.read_bytes(), custom)

    def test_rejects_redirected_etc(self):
        etc = self.root / 'etc'
        etc.rename(self.root / 'elsewhere')
        etc.symlink_to(self.root / 'elsewhere', target_is_directory=True)
        with self.assertRaises(OSError):
            steam_dns.prepare(self.root)
        self.assertEqual(list((self.root / 'elsewhere').iterdir()), [])

    def test_replace_failure_keeps_original_and_allows_retry(self):
        initial = b'# Resolver configuration file.\n'
        self.resolver.write_bytes(initial)
        with mock.patch.object(steam_dns.os, 'replace', side_effect=OSError('interrupted replace')):
            with self.assertRaisesRegex(OSError, 'interrupted replace'):
                steam_dns.prepare(self.root)
        self.assertEqual(self.resolver.read_bytes(), initial)
        self.assertEqual(list(self.resolver.parent.iterdir()), [self.resolver])
        steam_dns.prepare(self.root)
        steam_dns.verify(self.root)
